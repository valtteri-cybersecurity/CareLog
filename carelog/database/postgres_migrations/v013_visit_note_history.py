def upgrade(cursor):
    # updated_at tells when the content of a note was last changed. The
    # column is added in three steps: existing notes get their created_at
    # first, because they have not been edited, and only then the column
    # becomes NOT NULL. The history trigger is created later in this
    # migration, so this UPDATE writes no history rows.
    cursor.execute("""
        ALTER TABLE visit_notes
        ADD COLUMN updated_at TIMESTAMP NULL
    """)

    cursor.execute("""
        UPDATE visit_notes
        SET updated_at = created_at
    """)

    cursor.execute("""
        ALTER TABLE visit_notes
        ALTER COLUMN updated_at SET DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
        ALTER COLUMN updated_at SET NOT NULL
    """)

    # One row for every change of a note's content: the text before and
    # after the change. RESTRICT keeps the history: a note with history
    # cannot be deleted.
    #
    # edited_by_user_id stays NULL until CareLog has authentication. Only
    # an authenticated user may be saved here later. The shared database
    # account carelog_app does not tell who made the change.
    cursor.execute("""
        CREATE TABLE visit_note_history (
            id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            note_id INT NOT NULL,
            old_content TEXT NOT NULL,
            new_content TEXT NOT NULL,
            edited_at TIMESTAMP NOT NULL
                DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
            edited_by_user_id INT NULL,

            FOREIGN KEY (note_id)
                REFERENCES visit_notes(id)
                ON DELETE RESTRICT,

            FOREIGN KEY (edited_by_user_id)
                REFERENCES users(id)
                ON DELETE RESTRICT
        )
    """)

    # The history of one note is read by note_id
    cursor.execute("""
        CREATE INDEX idx_visit_note_history_note_id
        ON visit_note_history (note_id)
    """)

    # The trigger function runs before every UPDATE of a note.
    #
    # SECURITY DEFINER: the function runs with the rights of its owner,
    # the migration account. That is how it can write the history table,
    # although carelog_app may only read it.
    #
    # SET search_path: a SECURITY DEFINER function must not find objects
    # through the caller's search path, because the caller could create a
    # fake table or function with the same name. pg_catalog holds the
    # built-in functions, pg_temp comes last, and the history table is
    # written with its schema name public.
    #
    # IS DISTINCT FROM also works with NULL values. An UPDATE that keeps
    # the same text writes no history row and keeps updated_at.
    cursor.execute("""
        CREATE FUNCTION public.save_visit_note_history()
        RETURNS trigger
        LANGUAGE plpgsql
        SECURITY DEFINER
        SET search_path = pg_catalog, pg_temp
        AS $$
        BEGIN
            IF NEW.content IS DISTINCT FROM OLD.content THEN
                NEW.updated_at := CURRENT_TIMESTAMP AT TIME ZONE 'UTC';

                INSERT INTO public.visit_note_history
                    (note_id, old_content, new_content, edited_at)
                VALUES
                    (OLD.id, OLD.content, NEW.content, NEW.updated_at);
            END IF;

            RETURN NEW;
        END;
        $$
    """)

    # A new function can be executed by everyone (PUBLIC) by default.
    # Only the trigger needs it, and a trigger works without this right.
    cursor.execute("""
        REVOKE ALL ON FUNCTION public.save_visit_note_history() FROM PUBLIC
    """)

    # The trigger runs in the same transaction as the UPDATE. If the
    # UPDATE fails or is rolled back, the history row is rolled back too.
    # The UPDATE locks the note row, so concurrent edits are saved one at
    # a time, and each history row starts from the latest saved text.
    cursor.execute("""
        CREATE TRIGGER trg_visit_notes_history
            BEFORE UPDATE ON visit_notes
            FOR EACH ROW
            EXECUTE FUNCTION public.save_visit_note_history()
    """)
