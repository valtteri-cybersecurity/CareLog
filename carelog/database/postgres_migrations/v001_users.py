def upgrade(cursor):
    # PostgreSQL has no ON UPDATE CURRENT_TIMESTAMP like MySQL. This
    # trigger function sets updated_at to the current UTC time whenever a
    # row is updated. The clients and visits tables use it too.
    cursor.execute("""
        CREATE FUNCTION set_updated_at()
        RETURNS trigger
        LANGUAGE plpgsql
        AS $$
        BEGIN
            NEW.updated_at := CURRENT_TIMESTAMP AT TIME ZONE 'UTC';
            RETURN NEW;
        END;
        $$
    """)

    # role is a VARCHAR with a CHECK constraint instead of a MySQL ENUM.
    # Times are stored in UTC without a time zone, as in the MySQL version.
    cursor.execute("""
        CREATE TABLE users (
            id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email VARCHAR(254) NOT NULL,
            display_name VARCHAR(150) NOT NULL,
            password_hash VARCHAR(255) NOT NULL,
            role VARCHAR(20) NOT NULL DEFAULT 'worker',
            is_active BOOLEAN NOT NULL DEFAULT TRUE,
            created_at TIMESTAMP NOT NULL
                DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
            updated_at TIMESTAMP NOT NULL
                DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),

            CONSTRAINT chk_users_role
                CHECK (role IN ('admin', 'worker'))
        )
    """)

    # MySQL compared the emails without letter case, so the same address
    # in other letters was a duplicate. The index on lower(email) keeps
    # that rule in PostgreSQL.
    cursor.execute("""
        CREATE UNIQUE INDEX uq_users_email ON users (lower(email))
    """)

    cursor.execute("""
        CREATE TRIGGER trg_users_updated_at
            BEFORE UPDATE ON users
            FOR EACH ROW
            EXECUTE FUNCTION set_updated_at()
    """)
