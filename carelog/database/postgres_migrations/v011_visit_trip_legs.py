def upgrade(cursor):
    # The legs of the trip actually driven for one visit. Saved trips in
    # the trips table are only suggestions; their values are copied here.
    # RESTRICT keeps the history: a visit with legs cannot be deleted.
    cursor.execute("""
        CREATE TABLE visit_trip_legs (
            id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            visit_id INT NOT NULL,
            position INT NOT NULL,
            start_location VARCHAR(255) NOT NULL,
            destination VARCHAR(255) NOT NULL,
            distance_km DECIMAL(10, 2) NULL,

            CONSTRAINT uq_trip_legs_visit_position
                UNIQUE (visit_id, position),

            CONSTRAINT chk_trip_legs_position
                CHECK (position > 0),

            CONSTRAINT chk_trip_legs_distance
                CHECK (distance_km >= 0),

            FOREIGN KEY (visit_id)
                REFERENCES visits(id)
                ON DELETE RESTRICT
        )
    """)
